#!/usr/bin/env python3
"""Deterministic daily/weekly stability audit for monthly XAUUSD OHLC proxy trades.

Research-only diagnostics. Input trade CSVs are assumed to have been generated by
an explicitly documented proxy. This tool does not infer fills, alter trade rows,
select a trailing rule, or authorize live execution.

The chronological trade-equity curve is an *independent-candidate sequence*, not
a portfolio curve, whenever candidate trades overlap. Daily/weekly aggregates are
grouped by UTC exit date; unresolved rows are excluded from closed-trade R totals
and counted separately.
"""
import argparse
import csv
import hashlib
import json
import math
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path


SCENARIOS = ("fixed", "v1", "v3")


def parse_time(value, field, row_number):
    if not value:
        return None
    text = str(value).strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    try:
        dt = datetime.fromisoformat(text)
    except ValueError as exc:
        raise ValueError(f"invalid {field} on row {row_number}: {value!r}") from exc
    if dt.tzinfo is None:
        raise ValueError(f"{field} lacks timezone on row {row_number}: {value!r}")
    return dt.astimezone(timezone.utc)


def parse_float(value, field, row_number):
    if value is None or str(value).strip() == "":
        return None
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"invalid {field} on row {row_number}: {value!r}") from exc
    if not math.isfinite(number):
        raise ValueError(f"non-finite {field} on row {row_number}: {value!r}")
    return number


def load_trades(path, scenario):
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    rows = []
    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        if not reader.fieldnames:
            raise ValueError(f"{path}: CSV has no header")
        aliases = {name.strip().lower(): name for name in reader.fieldnames}
        def field(*names):
            return next((aliases[n] for n in names if n in aliases), None)
        entry_col = field("entry_time_utc", "entry_utc")
        exit_col = field("exit_time_utc", "exit_utc")
        r_col = field("r_multiple", "r", "total_r")
        reason_col = field("exit_reason", "reason")
        direction_col = field("direction", "side")
        setup_col = field("setup_time_utc", "setup_utc")
        status_col = field("status", "trade_status")
        if not entry_col or not exit_col or not r_col:
            raise ValueError(f"{path}: required entry_time_utc, exit_time_utc, r_multiple columns missing")
        for n, raw in enumerate(reader, 2):
            entry = parse_time(raw.get(entry_col), entry_col, n)
            exit_time = parse_time(raw.get(exit_col), exit_col, n)
            r = parse_float(raw.get(r_col), r_col, n)
            reason = (raw.get(reason_col, "") if reason_col else "").strip()
            status = (raw.get(status_col, "") if status_col else "").strip().upper()
            closed = exit_time is not None and r is not None and status not in {"UNRESOLVED", "OPEN"}
            if closed and exit_time < entry:
                raise ValueError(f"{path}: exit precedes entry on row {n}")
            rows.append({
                "scenario": scenario,
                "row_number": n,
                "setup_time": parse_time(raw.get(setup_col), setup_col, n) if setup_col else None,
                "entry_time": entry,
                "exit_time": exit_time,
                "r": r if closed else None,
                "closed": closed,
                "reason": reason or ("UNRESOLVED" if not closed else "UNKNOWN"),
                "direction": (raw.get(direction_col, "") if direction_col else "").strip().upper() or "UNKNOWN",
            })
    return rows, digest


def profit_factor(values):
    gross_profit = sum(x for x in values if x > 0)
    gross_loss = -sum(x for x in values if x < 0)
    if gross_loss == 0:
        return "INF" if gross_profit > 0 else None
    return round(gross_profit / gross_loss, 6)


def max_drawdown(values):
    equity = 0.0
    peak = 0.0
    max_dd = 0.0
    for value in values:
        equity += value
        peak = max(peak, equity)
        max_dd = max(max_dd, peak - equity)
    return round(max_dd, 6)


def summarize(rows):
    closed = [r for r in rows if r["closed"]]
    values = [r["r"] for r in closed]
    wins = sum(x > 0 for x in values)
    losses = sum(x < 0 for x in values)
    flats = sum(x == 0 for x in values)
    return {
        "candidate_rows": len(rows),
        "closed_rows": len(closed),
        "unresolved_or_unscored_rows": len(rows) - len(closed),
        "wins": wins, "losses": losses, "flats": flats,
        "win_rate_pct_closed": round(100 * wins / len(closed), 4) if closed else None,
        "total_R": round(sum(values), 6),
        "average_R": round(sum(values) / len(values), 6) if values else None,
        "gross_profit_factor": profit_factor(values),
        "chronological_candidate_sequence_max_drawdown_R": max_drawdown(
            [r["r"] for r in sorted(closed, key=lambda x: (x["exit_time"], x["entry_time"] or x["exit_time"], x["row_number"]))]
        ),
        "overlap_warning": "Not portfolio drawdown: independent candidate intervals may overlap.",
    }


def aggregate_period(rows, period):
    buckets = defaultdict(list)
    for row in rows:
        if not row["closed"]:
            continue
        stamp = row["exit_time"]
        key = stamp.date().isoformat() if period == "day" else f"{stamp.isocalendar().year}-W{stamp.isocalendar().week:02d}"
        buckets[key].append(row)
    out = []
    cumulative = 0.0
    peak = 0.0
    for key in sorted(buckets):
        bucket = buckets[key]
        values = [r["r"] for r in bucket]
        wins = sum(x > 0 for x in values)
        total = sum(values)
        cumulative += total
        peak = max(peak, cumulative)
        out.append({
            "period_utc": key,
            "closed_trades": len(bucket),
            "wins": wins,
            "losses": sum(x < 0 for x in values),
            "flats": sum(x == 0 for x in values),
            "win_rate_pct": round(100 * wins / len(bucket), 4) if bucket else None,
            "total_R": round(total, 6),
            "average_R": round(total / len(bucket), 6) if bucket else None,
            "gross_profit_factor": profit_factor(values),
            "cumulative_period_end_R": round(cumulative, 6),
            "period_end_drawdown_R": round(peak - cumulative, 6),
        })
    return out


def breakdown(rows, field):
    buckets = defaultdict(list)
    for row in rows:
        if row["closed"]:
            buckets[row[field]].append(row["r"])
    result = []
    for name in sorted(buckets):
        vals = buckets[name]
        result.append({
            field: name,
            "closed_trades": len(vals),
            "wins": sum(x > 0 for x in vals),
            "losses": sum(x < 0 for x in vals),
            "flats": sum(x == 0 for x in vals),
            "total_R": round(sum(vals), 6),
            "average_R": round(sum(vals) / len(vals), 6),
            "gross_profit_factor": profit_factor(vals),
        })
    return result


def write_csv(path, rows):
    fields = list(rows[0]) if rows else ["period_utc", "closed_trades"]
    with path.open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixed-csv", required=True, type=Path)
    parser.add_argument("--v1-csv", required=True, type=Path)
    parser.add_argument("--v3-csv", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    if args.out.exists() and any(args.out.iterdir()):
        raise SystemExit("Refusing to overwrite non-empty output directory: " + str(args.out))

    paths = {"fixed": args.fixed_csv, "v1": args.v1_csv, "v3": args.v3_csv}
    all_rows = {}
    input_hashes = {}
    for scenario, path in paths.items():
        if not path.is_file():
            raise SystemExit(f"input CSV not found: {path}")
        all_rows[scenario], input_hashes[scenario] = load_trades(path, scenario)

    summaries = {}
    args.out.mkdir(parents=True, exist_ok=True)
    for scenario, rows in all_rows.items():
        summaries[scenario] = summarize(rows)
        write_csv(args.out / f"{scenario}_daily.csv", aggregate_period(rows, "day"))
        write_csv(args.out / f"{scenario}_weekly.csv", aggregate_period(rows, "week"))
        write_csv(args.out / f"{scenario}_by_direction.csv", breakdown(rows, "direction"))
        write_csv(args.out / f"{scenario}_by_exit_reason.csv", breakdown(rows, "reason"))

    summary = {
        "status": "RESEARCH_STABILITY_AUDIT_COMPLETE_NOT_CANONICAL",
        "research_only": True,
        "canonical": False,
        "inputs": {key: {"path": str(paths[key].resolve()), "sha256": input_hashes[key]} for key in SCENARIOS},
        "method": {
            "daily_and_weekly_grouping": "UTC exit time",
            "unresolved_rows": "excluded from closed-trade R totals; counted separately",
            "drawdown": "chronological independent-candidate R sequence and period-end daily/weekly equity; neither is portfolio drawdown when trades overlap",
            "costs": "not included unless already reflected in input rows",
            "selection": "no trailing variant selected; no source semantics inferred",
        },
        "scenarios": summaries,
        "interpretation_guardrail": "A one-month split is descriptive stability analysis, not a statistically validated edge. Do not tune or promote canonical rules from these results; reserve a fresh untouched holdout.",
        "artifacts": [f"{s}_{suffix}.csv" for s in SCENARIOS for suffix in ("daily", "weekly", "by_direction", "by_exit_reason")],
    }
    (args.out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    lines = [
        "# Monthly XAUUSD trailing stability audit", "",
        "**Research-only. Not canonical. Not a portfolio simulation when candidate intervals overlap.**", "",
        "## Scenario summary", "",
        "| Scenario | Closed | Unresolved/unscored | Win rate | Total R | Average R | Gross PF | Candidate-sequence max DD |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for scenario in SCENARIOS:
        s = summaries[scenario]
        lines.append(f"| {scenario.upper()} | {s['closed_rows']} | {s['unresolved_or_unscored_rows']} | {s['win_rate_pct_closed']}% | {s['total_R']} | {s['average_R']} | {s['gross_profit_factor']} | {s['chronological_candidate_sequence_max_drawdown_R']}R |")
    lines += [
        "", "## Reading the outputs", "",
        "- Daily and weekly files are grouped by UTC exit time, not entry/setup time.",
        "- Candidate-sequence drawdown is not a portfolio drawdown if trade intervals overlap.",
        "- Daily/weekly aggregation over a single approximately 30-day window is descriptive and can be sensitive to a few trades.",
        "- This tool does not validate fills, spread, slippage, commissions, swaps, or the author/source meaning of trailing.",
        "- Do not select V1/V3 from these outputs alone; keep source resolution separate and use an untouched fresh holdout after any rule freeze.", "",
    ]
    (args.out / "report.md").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"status": summary["status"], "out": str(args.out.resolve()), "input_hashes": input_hashes, "scenarios": summaries}, indent=2))


if __name__ == "__main__":
    main()
